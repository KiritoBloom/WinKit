//! Minimal COM/WMI helpers for hardware telemetry.
//!
//! `windows-sys` 0.59 does not generate the Wbem* COM interfaces, so this
//! module hand-rolls the exact vtable slot layout of the four interfaces
//! WinKit reads from (IWbemLocator, IWbemServices, IEnumWbemClassObject,
//! IWbemClassObject). The layouts are fixed by the Windows SDK and have not
//! changed for supported Windows releases. Only the slots actually used are
//! ever called; the others are never invoked.
//!
//! Everything here is synchronous and bounded: each `WmiSession::query`
//! call creates and releases its own COM session on the calling thread, so a
//! stalled provider can never poison another thread's state.

use std::ffi::c_void;

use windows_sys::core::{BSTR, GUID, HRESULT};
use windows_sys::Win32::System::Com::{
    CoCreateInstance, CoInitializeEx, CLSCTX_INPROC_SERVER, COINIT_APARTMENTTHREADED,
    COINIT_MULTITHREADED,
};
use windows_sys::Win32::System::Variant::{VariantClear, VARIANT};

use crate::errors::{ErrorKind, WinkitError};
use crate::log_warn;
use crate::utils::wide_to_string;

/// HRESULT for `RPC_E_CHANGED_MODE` (0x80010106). Not generated by
/// windows-sys, so declared here.
pub const RPC_E_CHANGED_MODE: HRESULT = -2_147_417_850;

const CLSID_WBEM_LOCATOR: GUID = GUID::from_u128(0x4590f811_1d3a_11d0_891f_00aa004b2e24);
const IID_IWBEM_LOCATOR: GUID = GUID::from_u128(0xdc12a687_737f_11cf_884d_00aa004b2e24);

/// `WBEM_S_NO_ERROR` (0) and the end-of-enumeration sentinel `WBEM_S_FALSE`
/// (1) are the only success codes WMI queries use here.
const WBEM_S_NO_ERROR: HRESULT = 0;

// VT_UI4 / VT_I4 / VT_R8 / VT_BSTR / VT_BOOL / VT_EMPTY / VT_NULL / VT_UI8 / VT_I8 / VT_UI2 / VT_I2
const VT_UI4: u16 = 19;
const VT_I4: u16 = 3;
const VT_R8: u16 = 5;
const VT_BSTR: u16 = 8;
const VT_BOOL: u16 = 11;
const VT_EMPTY: u16 = 0;
const VT_NULL: u16 = 1;
const VT_UI8: u16 = 21;
const VT_I8: u16 = 20;
const VT_UI2: u16 = 18;
const VT_I2: u16 = 2;
const VT_UI1: u16 = 17;
const VT_I1: u16 = 16;

/// Read a vtable slot from a COM interface pointer. Every slot is one
/// function pointer (`usize`-sized).
unsafe fn slot(iface: *mut c_void, index: usize) -> usize {
    let vtbl = *(iface as *const *const usize);
    *vtbl.add(index)
}

/// Call `IUnknown::Release` (slot 2).
unsafe fn release(iface: *mut c_void) -> u32 {
    type F = unsafe extern "system" fn(*mut c_void) -> u32;
    std::mem::transmute::<usize, F>(slot(iface, 2))(iface)
}

type ConnectServerFn = unsafe extern "system" fn(
    *mut c_void,
    BSTR,
    BSTR,
    BSTR,
    BSTR,
    i32,
    BSTR,
    *mut c_void,
    *mut *mut c_void,
) -> HRESULT;
type ExecQueryFn = unsafe extern "system" fn(
    *mut c_void,
    BSTR,
    BSTR,
    i32,
    *mut c_void,
    *mut *mut c_void,
) -> HRESULT;
type NextFn =
    unsafe extern "system" fn(*mut c_void, i32, u32, *mut *mut c_void, *mut u32) -> HRESULT;

/// COM apartment initialization guard. Initializes COM for the calling
/// thread (MTA, falling back to STA) and uninitializes on drop.
struct ComGuard {
    initialized: bool,
}

impl ComGuard {
    fn new() -> Self {
        let mut initialized = false;
        unsafe {
            let hr = CoInitializeEx(std::ptr::null(), COINIT_MULTITHREADED as u32);
            if hr == 0 || hr == 1 {
                initialized = true;
            } else if hr == RPC_E_CHANGED_MODE {
                let hr2 = CoInitializeEx(std::ptr::null(), COINIT_APARTMENTTHREADED as u32);
                if hr2 == 0 || hr2 == 1 {
                    initialized = true;
                }
            } else {
                log_warn!("CoInitializeEx failed with hr={hr:#x}; WMI unavailable");
            }
        }
        Self { initialized }
    }
}

impl Drop for ComGuard {
    fn drop(&mut self) {
        if self.initialized {
            unsafe { windows_sys::Win32::System::Com::CoUninitialize() };
        }
    }
}

/// A typed wrapper over `IWbemLocator`.
struct WbemLocator(*mut c_void);

impl Drop for WbemLocator {
    fn drop(&mut self) {
        unsafe { release(self.0) };
    }
}

